for (const width of [320, 390, 768, 1024, 1440])
  test(`diseño sin desbordes a ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'El sabor de Ushuaia' })).toBeVisible()
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
    ).toBe(true)
    await page.screenshot({ path: `test-results/catalog-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Ver Muzzarella, disponible' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.getByRole('dialog')).toHaveCSS('opacity', '1')
    const box = await page.getByRole('dialog').boundingBox()
    expect(box!.width).toBeLessThanOrEqual(width)
    await page.screenshot({ path: `test-results/modal-${width}.png` })
    await page.keyboard.press('Escape')
  })
